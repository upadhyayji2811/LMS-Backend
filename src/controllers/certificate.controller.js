/**
 * @file certificate.controller.js
 * @description Certificate generation, retrieval, and public verification.
 */

const Certificate = require("../models/Certificate.model");
const Enrollment = require("../models/Enrollment.model");
const Course = require("../models/Course.model");
const User = require("../models/User.model");
const { generateCertificate } = require("../utils/generateCertificate");
const { sendCertificateEmail } = require("../utils/sendEmail");

// ─── Generate Certificate ─────────────────────────────────────────────────────
/**
 * POST /api/certificates/:courseId/generate
 * Generates a PDF certificate when student has 100% course progress.
 */
const generateCertificateHandler = async (req, res) => {
  try {
    const { courseId } = req.params;

    // Verify enrollment and completion
    const enrollment = await Enrollment.findOne({
      user: req.user._id,
      course: courseId,
      paymentStatus: "completed",
    });

    if (!enrollment) {
      return res.status(403).json({
        success: false,
        message: "You are not enrolled in this course.",
      });
    }

    if (!enrollment.isCompleted) {
      return res.status(400).json({
        success: false,
        message: `Course not completed yet. Progress: ${enrollment.progress}%. Complete all lessons to get your certificate.`,
      });
    }

    // Check if certificate already exists
    const existingCertificate = await Certificate.findOne({
      user: req.user._id,
      course: courseId,
    });

    if (existingCertificate) {
      return res.status(200).json({
        success: true,
        message: "Certificate already issued.",
        certificate: existingCertificate,
      });
    }

    // Fetch course and instructor details
    const course = await Course.findById(courseId)
      .populate("instructor", "name")
      .populate("category", "name")
      .lean();

    if (!course) {
      return res.status(404).json({ success: false, message: "Course not found." });
    }

    // Generate PDF certificate
    console.log(`🏆 Generating certificate for ${req.user.name} — ${course.title}`);
    const { pdfUrl, publicId } = await generateCertificate({
      studentName: req.user.name,
      courseName: course.title,
      instructorName: course.instructor?.name || "LMS Instructor",
      categoryName: course.category?.name || "Game Development",
      issuedAt: new Date(),
      certificateId: undefined, // Auto-generated by schema default
    });

    // Save certificate to DB
    const certificate = await Certificate.create({
      user: req.user._id,
      course: courseId,
      pdfUrl,
      pdfPublicId: publicId,
      studentName: req.user.name,
      courseName: course.title,
      instructorName: course.instructor?.name || "LMS Instructor",
      categoryName: course.category?.name || "Game Development",
    });

    // Send certificate email (non-blocking)
    sendCertificateEmail(req.user, certificate).catch((err) =>
      console.warn("Certificate email failed:", err.message)
    );

    res.status(201).json({
      success: true,
      message: "Certificate generated successfully! 🎉 Check your email.",
      certificate,
    });
  } catch (err) {
    console.error("generateCertificate error:", err);
    res.status(500).json({
      success: false,
      message: err.message || "Failed to generate certificate.",
    });
  }
};

// ─── Get Certificate ──────────────────────────────────────────────────────────
/**
 * GET /api/certificates/:courseId
 * Returns the certificate for a specific course (if issued).
 */
const getCertificate = async (req, res) => {
  try {
    const { courseId } = req.params;

    const certificate = await Certificate.findOne({
      user: req.user._id,
      course: courseId,
    })
      .populate("user", "name email")
      .populate("course", "title thumbnail instructor")
      .lean();

    if (!certificate) {
      return res.status(404).json({
        success: false,
        message: "Certificate not found. Complete the course to earn your certificate.",
      });
    }

    const verificationUrl = `${process.env.CLIENT_URL || "http://localhost:3000"}/verify/${certificate.certificateId}`;

    res.status(200).json({
      success: true,
      certificate: {
        ...certificate,
        verificationUrl,
      },
    });
  } catch (err) {
    console.error("getCertificate error:", err);
    res.status(500).json({ success: false, message: "Failed to fetch certificate." });
  }
};

// ─── Get All My Certificates ──────────────────────────────────────────────────
/**
 * GET /api/certificates/my-certificates
 * Returns all certificates earned by the student.
 */
const getMyCertificates = async (req, res) => {
  try {
    const certificates = await Certificate.find({
      user: req.user._id,
      isValid: true,
    })
      .populate("course", "title thumbnail category")
      .sort({ issuedAt: -1 })
      .lean();

    res.status(200).json({
      success: true,
      count: certificates.length,
      certificates: certificates.map((cert) => ({
        ...cert,
        verificationUrl: `${process.env.CLIENT_URL || "http://localhost:3000"}/verify/${cert.certificateId}`,
      })),
    });
  } catch (err) {
    console.error("getMyCertificates error:", err);
    res.status(500).json({ success: false, message: "Failed to fetch certificates." });
  }
};

// ─── Public Certificate Verification ─────────────────────────────────────────
/**
 * GET /api/certificates/verify/:certificateId
 * Public endpoint — anyone can verify a certificate by its unique ID.
 */
const verifyCertificate = async (req, res) => {
  try {
    const { certificateId } = req.params;

    const certificate = await Certificate.findOne({ certificateId })
      .populate("user", "name")
      .populate("course", "title thumbnail instructor category")
      .lean();

    if (!certificate) {
      return res.status(404).json({
        success: false,
        message: "Certificate not found. This ID may be invalid.",
        isValid: false,
      });
    }

    if (!certificate.isValid) {
      return res.status(200).json({
        success: false,
        message: "This certificate has been revoked.",
        isValid: false,
        revokedAt: certificate.revokedAt,
        revokedReason: certificate.revokedReason,
      });
    }

    res.status(200).json({
      success: true,
      isValid: true,
      message: "Certificate is valid and authentic. ✅",
      certificate: {
        certificateId: certificate.certificateId,
        studentName: certificate.studentName,
        courseName: certificate.courseName,
        instructorName: certificate.instructorName,
        categoryName: certificate.categoryName,
        issuedAt: certificate.issuedAt,
        pdfUrl: certificate.pdfUrl,
        verificationUrl: `${process.env.CLIENT_URL || "http://localhost:3000"}/verify/${certificateId}`,
      },
    });
  } catch (err) {
    console.error("verifyCertificate error:", err);
    res.status(500).json({ success: false, message: "Failed to verify certificate." });
  }
};

module.exports = {
  generateCertificate: generateCertificateHandler,
  getCertificate,
  getMyCertificates,
  verifyCertificate,
};
